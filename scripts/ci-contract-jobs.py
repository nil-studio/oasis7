#!/usr/bin/env python3
"""Generate and verify native contract jobs in CI workflows."""

import argparse
import difflib
import json
import os
from pathlib import Path
import re
import stat
import sys
import tempfile

BEGIN_MARKER = "  # BEGIN GENERATED contract-jobs-v1"
HEADER_COMMENT = "  # Generated by scripts/ci-contract-jobs.py. Do not edit directly."
END_MARKER = "  # END GENERATED contract-jobs-v1"
MANAGED_GROUPS = ("operational_contracts", "packaging_contracts")

# Linux mold linker setup required for native host Cargo linking in packaging contracts.
GROUPS_WITH_MOLD = {"packaging_contracts"}


def render_job(group: str) -> str:
    job_id = group.replace("_", "-")
    mold_prefix = ""
    if group in GROUPS_WITH_MOLD:
        mold_prefix = (
            "      - *linux-mold-tools-checkout\n"
            "      - name: Configure mold for Linux host linking\n"
            "        uses: ./.github/actions/setup-linux-mold\n"
        )
    rust_setup = (
        '      - name: Install Rust for packaging contract fixtures\n'
        '        run: rustup toolchain install "$RUST_TOOLCHAIN" --profile minimal --component rustfmt --component clippy\n'
    ) if group == "packaging_contracts" else ""
    return (
        f"  {job_id}:\n"
        f"    needs: select\n"
        f"    if: >-\n"
        f"      always() && !cancelled() && needs.select.result == 'success' &&\n"
        f"      (needs.select.outputs.run_{group} == 'true' ||\n"
        f"       fromJSON(needs.select.outputs.plan).scope == 'full')\n"
        f"    runs-on: ubuntu-24.04\n"
        f"    steps:\n"
        f"{mold_prefix}"
        f"      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1\n"
        f"        with:\n"
        f"          ref: ${{{{ needs.select.outputs.tested_sha }}}}\n"
        f"          fetch-depth: 0\n"
        f"          persist-credentials: false\n"
        f"      - uses: actions/setup-python@6d4fd22b20465ccc0f7354476588e8df7c9ca0e0 # v7\n"
        f"        with:\n"
        f"          python-version: '3.12'\n"
        f"{rust_setup}"
        f"      - name: Execute selected group\n"
        f"        shell: bash\n"
        f"        env:\n"
        f"          CI_VERBOSE: \"1\"\n"
        f"          OASIS7_PRODUCT_DOC_BASE: ${{{{ needs.select.outputs.range_base }}}}\n"
        f"          OASIS7_PRODUCT_DOC_HEAD: ${{{{ needs.select.outputs.tested_sha }}}}\n"
        f"        run: bash ./scripts/ci-tests.sh required --group \"{group}\" --repo-root \"$GITHUB_WORKSPACE\""
    )


def render_managed_block(groups=MANAGED_GROUPS) -> str:
    jobs = [render_job(group) for group in groups]
    body = "\n\n".join(jobs)
    return f"{BEGIN_MARKER}\n{HEADER_COMMENT}\n{body}\n{END_MARKER}"


def validate_repo_and_paths(repo_root: Path):
    if not repo_root.exists() or not repo_root.is_dir():
        sys.stderr.write(f"Error: repository root {repo_root} is not an existing directory\n")
        sys.exit(2)

    workflow_path = repo_root / ".github" / "workflows" / "rust.yml"
    scope_path = repo_root / "scripts" / "ci-required-scope.json"

    for p in (workflow_path, scope_path):
        if p.is_symlink():
            sys.stderr.write(f"Error: path {p} must not be a symlink\n")
            sys.exit(2)
        if not p.is_file():
            sys.stderr.write(f"Error: path {p} must be an existing regular file\n")
            sys.exit(2)

        curr = p.parent
        while curr != repo_root and curr != curr.parent:
            if curr.is_symlink():
                sys.stderr.write(f"Error: parent directory {curr} must not be a symlink\n")
                sys.exit(2)
            curr = curr.parent

    try:
        workflow_path.resolve().relative_to(repo_root.resolve())
    except ValueError:
        sys.stderr.write(f"Error: workflow path {workflow_path} is outside repository root {repo_root}\n")
        sys.exit(2)

    return workflow_path, scope_path


def validate_scope_groups(scope_path: Path):
    try:
        data = json.loads(scope_path.read_text(encoding="utf-8"))
    except Exception as e:
        sys.stderr.write(f"Error reading scope configuration {scope_path}: {e}\n")
        sys.exit(2)

    groups = data.get("groups")
    if not isinstance(groups, list):
        sys.stderr.write(f"Error: 'groups' key missing or not a list in {scope_path}\n")
        sys.exit(2)

    for g in MANAGED_GROUPS:
        if g not in groups:
            sys.stderr.write(f"Error: managed group '{g}' not found in {scope_path} groups\n")
            sys.exit(2)


def parse_and_validate_workflow(content: str):
    if "\r\n" in content:
        sys.stderr.write("Error: CRLF line endings detected in workflow; LF required\n")
        sys.exit(2)

    jobs_marker = "\njobs:\n"
    jobs_idx = content.find(jobs_marker)
    if jobs_idx == -1:
        sys.stderr.write("Error: 'jobs:' section not found in workflow\n")
        sys.exit(2)

    begin_count = content.count(BEGIN_MARKER)
    end_count = content.count(END_MARKER)

    if begin_count == 0 or end_count == 0:
        sys.stderr.write(f"Error: missing markers ({BEGIN_MARKER.strip()} or {END_MARKER.strip()}) in workflow\n")
        sys.exit(2)

    if begin_count > 1 or end_count > 1:
        sys.stderr.write("Error: duplicate markers detected in workflow\n")
        sys.exit(2)

    begin_pos = content.find(BEGIN_MARKER)
    end_pos = content.find(END_MARKER)

    if end_pos < begin_pos:
        sys.stderr.write("Error: markers are reversed or nested\n")
        sys.exit(2)

    if begin_pos < jobs_idx:
        sys.stderr.write("Error: managed markers must be inside 'jobs:' section\n")
        sys.exit(2)

    prefix = content[:begin_pos]
    suffix = content[end_pos + len(END_MARKER):]

    for g in MANAGED_GROUPS:
        job_id = g.replace("_", "-")
        pattern = rf"^  {re.escape(job_id)}:\s*$"
        if re.search(pattern, prefix, re.M) or re.search(pattern, suffix, re.M):
            sys.stderr.write(f"Error: job '{job_id}' is defined outside managed markers\n")
            sys.exit(2)

    managed_content = content[begin_pos : end_pos + len(END_MARKER)]
    return begin_pos, end_pos + len(END_MARKER), managed_content


def check_drift(current_managed: str, expected_managed: str) -> bool:
    if current_managed == expected_managed:
        return False

    diff = difflib.unified_diff(
        current_managed.splitlines(keepends=True),
        expected_managed.splitlines(keepends=True),
        fromfile="managed:rust.yml",
        tofile="generated",
    )
    sys.stdout.writelines(diff)
    sys.stdout.write("Drift detected in managed contract jobs in .github/workflows/rust.yml.\n")
    sys.stdout.write("To synchronize, run:\n  python3 scripts/ci-contract-jobs.py --write\n")
    return True


def write_workflow(workflow_path: Path, new_content: str, original_bytes: bytes):
    target_dir = workflow_path.parent
    st = workflow_path.stat()

    fd, temp_file_path = tempfile.mkstemp(
        prefix=".rust.yml.tmp-",
        dir=target_dir,
        text=False
    )
    temp_path = Path(temp_file_path)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(new_content.encode("utf-8"))
            f.flush()
            os.fsync(f.fileno())

        temp_path.chmod(stat.S_IMODE(st.st_mode))

        current_bytes = workflow_path.read_bytes()
        if current_bytes != original_bytes:
            sys.stderr.write("Error: concurrent modification detected in target workflow file; aborting write\n")
            sys.exit(2)

        os.replace(temp_path, workflow_path)
        print("Updated .github/workflows/rust.yml with generated contract jobs.")
    except BaseException:
        if temp_path.exists():
            try:
                temp_path.unlink()
            except OSError:
                pass
        raise


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Generate or verify native contract jobs in CI workflows."
    )
    mode_group = parser.add_mutually_exclusive_group(required=True)
    mode_group.add_argument(
        "--check",
        action="store_true",
        help="Verify managed contract jobs in .github/workflows/rust.yml without modifying files.",
    )
    mode_group.add_argument(
        "--write",
        action="store_true",
        help="Update managed contract jobs in .github/workflows/rust.yml atomically.",
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
        help="Path to repository root (defaults to parent of scripts/).",
    )

    args = parser.parse_args(argv)

    workflow_path, scope_path = validate_repo_and_paths(args.repo_root)
    validate_scope_groups(scope_path)

    expected_managed = render_managed_block()

    original_bytes = workflow_path.read_bytes()
    try:
        original_text = original_bytes.decode("utf-8")
    except UnicodeDecodeError as e:
        sys.stderr.write(f"Error decoding {workflow_path} as UTF-8: {e}\n")
        sys.exit(2)

    begin_idx, end_idx, current_managed = parse_and_validate_workflow(original_text)

    if args.check:
        has_drift = check_drift(current_managed, expected_managed)
        if has_drift:
            sys.exit(1)
        print("CI contract jobs are up to date.")
        sys.exit(0)
    elif args.write:
        if current_managed == expected_managed:
            print("CI contract jobs are already up to date.")
            sys.exit(0)

        new_content = original_text[:begin_idx] + expected_managed + original_text[end_idx:]
        write_workflow(workflow_path, new_content, original_bytes)
        sys.exit(0)


if __name__ == "__main__":
    main()
