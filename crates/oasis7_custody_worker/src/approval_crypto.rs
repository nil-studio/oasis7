//! Native approval verification against operator-configured pins.
//! WebCrypto and the native strict Ed25519 rules must both accept the same bytes.
use base64::{Engine, engine::general_purpose::URL_SAFE_NO_PAD};
use ed25519_dalek::{Signature, VerifyingKey};
use js_sys::{Array, Reflect, Uint8Array};
use wasm_bindgen::{JsCast, JsValue};
use wasm_bindgen_futures::JsFuture;
use web_sys::{Crypto, CryptoKey};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SignatureRejected;

fn crypto() -> Result<Crypto, SignatureRejected> {
    Reflect::get(&js_sys::global(), &JsValue::from_str("crypto"))
        .map_err(|_| SignatureRejected)?
        .dyn_into()
        .map_err(|_| SignatureRejected)
}

/// Verify canonical Rust bytes; never reconstruct a signing image in JavaScript.
/// No key is discovered from a request URL, and no private key is imported here.
pub async fn verify_ed25519(
    public_key_hex: &str,
    signature_base64url: &str,
    message: &[u8],
) -> Result<(), SignatureRejected> {
    if public_key_hex.len() != 64 || signature_base64url.len() != 86 {
        return Err(SignatureRejected);
    }
    let public_key: [u8; 32] = hex::decode(public_key_hex)
        .map_err(|_| SignatureRejected)?
        .try_into()
        .map_err(|_| SignatureRejected)?;
    if hex::encode(public_key) != public_key_hex {
        return Err(SignatureRejected);
    }
    let signature = URL_SAFE_NO_PAD
        .decode(signature_base64url)
        .map_err(|_| SignatureRejected)?;
    if signature.len() != 64 || URL_SAFE_NO_PAD.encode(&signature) != signature_base64url {
        return Err(SignatureRejected);
    }
    let native_key = VerifyingKey::from_bytes(&public_key).map_err(|_| SignatureRejected)?;
    if native_key.is_weak() {
        return Err(SignatureRejected);
    }
    let native_signature = Signature::from_slice(&signature).map_err(|_| SignatureRejected)?;
    native_key
        .verify_strict(message, &native_signature)
        .map_err(|_| SignatureRejected)?;

    let subtle = crypto()?.subtle();
    let usages = Array::new();
    usages.push(&JsValue::from_str("verify"));
    let raw = Uint8Array::from(public_key.as_slice());
    let import = subtle
        .import_key_with_str("raw", raw.as_ref(), "Ed25519", false, usages.as_ref())
        .map_err(|_| SignatureRejected)?;
    let key: CryptoKey = JsFuture::from(import)
        .await
        .map_err(|_| SignatureRejected)?
        .dyn_into()
        .map_err(|_| SignatureRejected)?;
    let verified = JsFuture::from(
        subtle
            .verify_with_str_and_u8_array_and_u8_array("Ed25519", &key, &signature, message)
            .map_err(|_| SignatureRejected)?,
    )
    .await
    .map_err(|_| SignatureRejected)?;
    if verified.as_bool() == Some(true) {
        Ok(())
    } else {
        Err(SignatureRejected)
    }
}

/// Generated by the Owner adapter, never supplied by an HTTP caller.
pub fn verification_nonce() -> Result<String, SignatureRejected> {
    let mut nonce = [0_u8; 32];
    crypto()?
        .get_random_values_with_u8_array(&mut nonce)
        .map_err(|_| SignatureRejected)?;
    Ok(hex::encode(nonce))
}
