use super::{
    ChainConsensusNetworkHeadStatus, ChainFinalityLatencyStatus, ChainInboundTimingRejectionsStatus,
};
use serde::Serialize;

#[derive(Debug, Serialize)]
pub(crate) struct ChainConsensusStatus {
    pub(crate) slot: u64,
    pub(crate) epoch: u64,
    pub(crate) ticks_per_slot: u64,
    pub(crate) tick_phase: u64,
    pub(crate) proposal_tick_phase: u64,
    pub(crate) last_observed_slot: u64,
    pub(crate) missed_slot_count: u64,
    pub(crate) last_observed_tick: u64,
    pub(crate) missed_tick_count: u64,
    pub(crate) adaptive_tick_scheduler_enabled: bool,
    pub(crate) latest_height: u64,
    pub(crate) committed_height: u64,
    pub(crate) last_committed_at_ms: Option<i64>,
    pub(crate) last_commit_age_ms: Option<i64>,
    pub(crate) network_committed_height: u64,
    pub(crate) replication_enabled: bool,
    pub(crate) replication_persisted_height: u64,
    pub(crate) replication_gap_sync_blocked_height: Option<u64>,
    pub(crate) replication_gap_sync_blocked_reason: Option<String>,
    pub(crate) replication_gap_sync_repair_attempt_height: Option<u64>,
    pub(crate) replication_gap_sync_repair_attempt_summary: Option<String>,
    pub(crate) replication_gap_sync_repair_attempt_route_snapshot:
        Option<oasis7_node::NodeReplicationGapSyncRouteSnapshot>,
    pub(crate) storage_challenge_network_degraded_height: Option<u64>,
    pub(crate) storage_challenge_network_degraded_reason: Option<String>,
    pub(crate) state_sync_fallback_required: bool,
    pub(crate) state_sync_snapshot_available: bool,
    pub(crate) state_sync_trusted_checkpoint_required_height: Option<u64>,
    pub(crate) state_sync_fallback_reason: Option<String>,
    pub(crate) consensus_participation_held: bool,
    pub(crate) consensus_participation_hold_reason: Option<String>,
    pub(crate) recent_finality_latency: ChainFinalityLatencyStatus,
    pub(crate) pending_proposal: Option<ChainPendingProposalStatus>,
    pub(crate) pending_consensus_actions: ChainPendingConsensusActionsStatus,
    pub(crate) inbound_timing_rejections: ChainInboundTimingRejectionsStatus,
    pub(crate) last_status: Option<String>,
    pub(crate) last_block_hash: Option<String>,
    pub(crate) last_execution_height: u64,
    pub(crate) last_execution_block_hash: Option<String>,
    pub(crate) last_execution_state_root: Option<String>,
    pub(crate) known_peer_heads: usize,
    pub(crate) validator_set_hash: String,
    pub(crate) validator_stake_root: String,
    pub(crate) validator_stake_proof_count: usize,
    pub(crate) misbehavior_evidence_count: usize,
    pub(crate) slashing_intent_count: usize,
    pub(crate) pending_slashing_intent_count: usize,
    pub(crate) slashing_receipt_count: usize,
    pub(crate) applied_slashing_receipt_count: usize,
    pub(crate) quarantined_validator_count: usize,
    pub(crate) slashable_stake_total: u64,
    pub(crate) network_head: ChainConsensusNetworkHeadStatus,
}

#[derive(Debug, Serialize)]
pub(crate) struct ChainPendingProposalStatus {
    pub(crate) height: u64,
    pub(crate) slot: u64,
    pub(crate) epoch: u64,
    pub(crate) proposer_id: String,
    pub(crate) opened_at_ms: i64,
    pub(crate) age_ms: i64,
    pub(crate) action_count: usize,
    pub(crate) action_payload_bytes: usize,
    pub(crate) attestation_count: usize,
    pub(crate) approved_stake: u64,
    pub(crate) rejected_stake: u64,
    pub(crate) required_stake: u64,
    pub(crate) total_stake: u64,
    pub(crate) approval_progress_bps: u16,
    pub(crate) rejection_progress_bps: u16,
    pub(crate) remaining_approval_stake: u64,
    pub(crate) status: String,
}

#[derive(Debug, Serialize)]
pub(crate) struct ChainPendingConsensusActionsStatus {
    pub(crate) queued_action_count: usize,
    pub(crate) queued_payload_bytes: usize,
    pub(crate) reserved_requeue_action_count: usize,
    pub(crate) reserved_requeue_payload_bytes: usize,
    pub(crate) available_capacity: usize,
    pub(crate) max_capacity: usize,
    pub(crate) submit_buffer_action_count: usize,
    pub(crate) submit_buffer_payload_bytes: usize,
    pub(crate) submit_buffer_max_capacity: usize,
}
