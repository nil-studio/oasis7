export function browserGameDiagnostic(failure, fallbackStage = "entry_inspect") {
  const code = clientCodes.has(failure?.code) ? failure.code : "game_operation_failed";
  const source = failure?.diagnostic;
  const stage = stages.has(source?.stage) ? source.stage : stages.has(fallbackStage) ? fallbackStage : "entry_inspect";
  const result = { code, stage, category: "unknown" };
  if (Number.isInteger(source?.httpStatus) && source.httpStatus >= 100 && source.httpStatus <= 599) result.httpStatus = source.httpStatus;
  if (clientCodes.has(source?.causeCode)) result.causeCode = source.causeCode;
  if (serverCodes.has(source?.serverCode)) result.serverCode = source.serverCode;
  if (["unknown", "history_unavailable", "pending", "received", "committed", "rejected", "expired"].includes(source?.outcome)) result.outcome = source.outcome;
  if (result.outcome === "history_unavailable") result.category = "history_unavailable";
  else if (result.outcome === "unknown") result.category = "unknown";
  else if (["owner_operation_pending", "participant_registration_pending", "operation_pending"].includes(code) || result.serverCode === "operation_pending") result.category = "pending";
  else if (["owner_operation_rejected", "participant_registration_rejected"].includes(code)) result.category = "rejected";
  else if (["owner_operation_expired", "participant_registration_expired"].includes(code)) result.category = "expired";
  else if (Object.hasOwn(participantReadCategories, result.serverCode)) result.category = participantReadCategories[result.serverCode];
  else if (code.includes("timeout")) result.category = "timeout";
  else if (code === "participant_network_failed") result.category = "network";
  else if (code.includes("storage") || code.includes("locks")) result.category = "storage";
  else if (code.includes("proof") || code.includes("signing")) result.category = "proof";
  else if ([401, 403].includes(result.httpStatus) || ["authentication_failed", "session_expired", "csrf_failed", "origin_rejected", "reauth_required", "executor_operation_not_allowed", "owner_control_operation_not_allowed"].includes(result.serverCode) || code.includes("mismatch") || code.includes("consent") || code.includes("account_changed")) result.category = "permission";
  else if (["owner_control_unavailable", "participant_unavailable", "executor_control_unavailable", "not_found"].includes(result.serverCode) || code.includes("configuration") || code.includes("discovery") || code === "game_protocol_unavailable") result.category = "deployment";
  return Object.freeze(result);
}
export function browserGameErrorStage(error, stage) {
  const diagnostic = browserGameDiagnostic({ code: error?.code, diagnostic: { ...error?.diagnostic, stage } }, stage);
  const safe = new Error(diagnostic.code); safe.code = diagnostic.code; safe.diagnostic = diagnostic; return safe;
}
export async function atBrowserGameStage(stage, action) {
  try { return await action(); } catch (error) { throw browserGameErrorStage(error, stage); }
}
export function gatewayFailureDiagnostic(value, httpStatus, stage) {
  return browserGameDiagnostic({ code: "participant_request_failed", diagnostic: { httpStatus, stage,
    serverCode: value?.api_version === 2 && value?.ok === false ? value.error_code : undefined } }, stage);
}
