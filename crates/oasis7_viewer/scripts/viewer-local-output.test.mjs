test("the real finalizer and copy consumer publish fresh isolated outputs without changing sources", t => {
  const f = producerFixture(t);
  for (let pass = 0; pass < 2; pass++) {
    const result = f.run();
    assert.equal(result.status, 0, result.stdout + result.stderr);
    assert.deepEqual(snapshot(f.viewer), f.source);
    assert.match(readFileSync(join(f.output, 'dist/release/viewer.js'), 'utf8'), /currentCandidate/);
    assert.match(readFileSync(join(f.output, 'bundles/release/viewer.js'), 'utf8'), /currentCandidate/);
    assert.ok(existsSync(join(f.output, 'dist/release/browser-game-client/oasis7_browser_game_client_bg.wasm')));
    assert.ok(existsSync(join(f.output, 'dist/release/pixel-world-bridge/webgl2/pixel_world_bridge_bindgen_bg.wasm')));
  }
  const commands = readFileSync(join(f.root, 'commands.jsonl'), 'utf8').trim().split('\n').map(JSON.parse);
  assert.equal(commands.filter(x => x.role === 'npm').length, 2, 'a local run cannot reuse an earlier dist as its real build');
  assert.equal(commands.filter(x => x.role === 'cargo').length, 4);
  for (const command of commands.filter(x => x.role === 'cargo')) {
    assert.equal(command.offline, 'true');
    assert.ok(command.args.includes('--locked'));
    assert.equal(command.args.includes('--target-dir'), false);
  }
});

test("failed build commands preserve source bytes and do not produce a successful dist manifest", t => {
  for (const failing of ['npm', 'cargo']) {
    const f = producerFixture(t);
    const result = f.run({ VIEWER_IO_FIXTURE_FAIL: failing });
    assert.notEqual(result.status, 0);
    assert.deepEqual(snapshot(f.viewer), f.source);
    assert.equal(existsSync(join(f.output, 'dist/release/.oasis7-viewer-dist-manifest.json')), false);
  }
});

test("a redirected output subtree is rejected before any tool is launched", t => {
  const f = producerFixture(t);
  symlinkSync(f.viewer, join(f.output, 'dist'));
  const result = f.run();
  assert.notEqual(result.status, 0);
  assert.match(result.stderr, /symlink/);
  assert.deepEqual(snapshot(f.viewer), f.source);
  assert.equal(existsSync(join(f.root, 'commands.jsonl')), false);
});
