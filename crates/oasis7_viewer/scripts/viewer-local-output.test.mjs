function write(path, content, executable = false) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content, executable ? { mode: 0o755 } : undefined);
}

function snapshot(root) {
  const result = {};
  function visit(directory, prefix = "") {
    for (const name of readdirSync(directory).sort()) {
      const path = join(directory, name);
      const relative = prefix + name;
      if (lstatSync(path).isDirectory()) visit(path, `${relative}/`);
      else result[relative] = readFileSync(path).toString("base64");
    }
  }
  visit(root);
  return result;
}

