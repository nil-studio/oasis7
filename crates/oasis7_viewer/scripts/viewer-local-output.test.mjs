import assert from "node:assert/strict";
import { copyFileSync, existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import test from "node:test";
import { localViewerOutputRoot, localViewerPath, viewerBuildPaths } from "./viewer-local-output.mjs";

const repo = resolve(import.meta.dirname, "../../..");

function temporary(t) {
  const root = mkdtempSync(join(tmpdir(), "viewer-local-output-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  return root;
}

function localEnvironment(t, root) {
  const before = { ...process.env };
  process.env.OASIS7_LOCAL_CHECK = "1";
  process.env.OASIS7_VIEWER_LOCAL_OUTPUT_ROOT = root;
  t.after(() => {
    for (const name of ["OASIS7_LOCAL_CHECK", "OASIS7_VIEWER_LOCAL_OUTPUT_ROOT"]) {
      if (before[name] === undefined) delete process.env[name];
      else process.env[name] = before[name];
    }
  });
}

test("default builds retain their existing paths and ignore a local-only output override", t => {
  localEnvironment(t, "/missing/output");
  process.env.OASIS7_LOCAL_CHECK = "0";
  assert.equal(localViewerOutputRoot(), null);
  assert.equal(viewerBuildPaths().bundleDir, resolve(import.meta.dirname, "../.software-safe-build"));
  assert.equal(viewerBuildPaths("visual-test").distDir, resolve(import.meta.dirname, "../.viewer-test-dist"));
});

test("local producers and consumers share disjoint release, visual and report paths", t => {
  const root = temporary(t);
  localEnvironment(t, root);
  assert.deepEqual(viewerBuildPaths(), { local: true, bundleDir: join(root, "bundles/release"), distDir: join(root, "dist/release") });
  assert.deepEqual(viewerBuildPaths("visual-test"), { local: true, bundleDir: join(root, "bundles/visual-test"), distDir: join(root, "dist/visual-test") });
  assert.equal(localViewerPath("reports", "browser-functional"), join(root, "reports/browser-functional"));
  assert.deepEqual(readdirSync(root), [], "resolving paths must not create outputs");
  assert.throws(() => localViewerPath("..", "escaped"), /stay inside/);
  assert.throws(() => viewerBuildPaths("unknown"), /unknown/);
});

test("missing, relative and symlinked output roots fail before use", t => {
  const root = temporary(t);
  localEnvironment(t, "relative");
  assert.throws(() => viewerBuildPaths(), /absolute owned/);
  process.env.OASIS7_VIEWER_LOCAL_OUTPUT_ROOT = join(root, "missing");
  assert.throws(() => viewerBuildPaths(), /ENOENT/);
  const actual = join(root, "actual");
  mkdirSync(actual);
  symlinkSync(actual, join(root, "linked"));
  process.env.OASIS7_VIEWER_LOCAL_OUTPUT_ROOT = join(root, "linked");
  assert.throws(() => viewerBuildPaths(), /without symlinks/);
});

test("a symlink in a generated output path cannot redirect a later consumer", t => {
  const root = temporary(t);
  localEnvironment(t, root);
  const outside = temporary(t);
  symlinkSync(outside, join(root, "bundles"));
  assert.throws(() => viewerBuildPaths(), /contains a symlink/);
  assert.deepEqual(readdirSync(outside), []);
});

