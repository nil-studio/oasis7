use super::super::*;

// Variant names preserve the public enum's Debug output.
#[allow(clippy::enum_variant_names)]
#[derive(Debug, PartialEq)]
pub(super) enum ModuleLifecycleView<'a> {
    ModuleArtifactDeployed {
        publisher_agent_id: &'a String,
        wasm_hash: &'a String,
        bytes_len: &'a u64,
        fee_kind: &'a ResourceKind,
        fee_amount: &'a i64,
    },
    ModuleInstalled {
        installer_agent_id: &'a String,
        instance_id: &'a String,
        module_id: &'a String,
        module_version: &'a String,
        wasm_hash: &'a String,
        install_target: &'a ModuleInstallTarget,
        active: &'a bool,
        proposal_id: &'a ProposalId,
        manifest_hash: &'a String,
        fee_kind: &'a ResourceKind,
        fee_amount: &'a i64,
    },
    ModuleUpgraded {
        upgrader_agent_id: &'a String,
        instance_id: &'a String,
        module_id: &'a String,
        from_module_version: &'a String,
        to_module_version: &'a String,
        wasm_hash: &'a String,
        install_target: &'a ModuleInstallTarget,
        active: &'a bool,
        proposal_id: &'a ProposalId,
        manifest_hash: &'a String,
        fee_kind: &'a ResourceKind,
        fee_amount: &'a i64,
    },
    ModuleReleaseRequested {
        request_id: &'a u64,
        requester_agent_id: &'a String,
        manifest: &'a ModuleManifest,
        activate: &'a bool,
        install_target: &'a ModuleInstallTarget,
        required_roles: &'a Vec<String>,
        profile_changes: &'a ModuleProfileChanges,
    },
    ModuleReleaseShadowed {
        request_id: &'a u64,
        operator_agent_id: &'a String,
        manifest_hash: &'a String,
    },
    ModuleReleaseAttested {
        request_id: &'a u64,
        operator_agent_id: &'a String,
        signer_node_id: &'a String,
        platform: &'a String,
        build_manifest_hash: &'a String,
        source_hash: &'a String,
        wasm_hash: &'a String,
        proof_cid: &'a String,
        builder_image_digest: &'a String,
        container_platform: &'a String,
        canonicalizer_version: &'a String,
    },
    ModuleReleaseRoleApproved {
        request_id: &'a u64,
        approver_agent_id: &'a String,
        role: &'a String,
    },
    ModuleReleaseRolesBound {
        operator_agent_id: &'a String,
        target_agent_id: &'a String,
        roles: &'a Vec<String>,
    },
    ModuleReleaseRejected {
        request_id: &'a u64,
        rejector_agent_id: &'a String,
        reason: &'a String,
    },
    ModuleReleaseApplied {
        request_id: &'a u64,
        operator_agent_id: &'a String,
        installer_agent_id: &'a String,
        instance_id: &'a String,
        module_id: &'a String,
        module_version: &'a String,
        proposal_id: &'a ProposalId,
        manifest_hash: &'a String,
    },
    ModuleRollbackApplied {
        operator_agent_id: &'a String,
        instance_id: &'a String,
        module_id: &'a String,
        from_module_version: &'a String,
        to_module_version: &'a String,
        wasm_hash: &'a String,
        from_wasm_hash: &'a Option<String>,
        from_release_request_id: &'a Option<u64>,
        install_target: &'a ModuleInstallTarget,
        active: &'a bool,
        proposal_id: &'a ProposalId,
        manifest_hash: &'a String,
        fee_kind: &'a ResourceKind,
        fee_amount: &'a i64,
    },
    ModuleArtifactListed {
        seller_agent_id: &'a String,
        wasm_hash: &'a String,
        price_kind: &'a ResourceKind,
        price_amount: &'a i64,
        order_id: &'a u64,
        fee_kind: &'a ResourceKind,
        fee_amount: &'a i64,
    },
    ModuleArtifactDelisted {
        seller_agent_id: &'a String,
        wasm_hash: &'a String,
        order_id: &'a Option<u64>,
        fee_kind: &'a ResourceKind,
        fee_amount: &'a i64,
    },
    ModuleArtifactDestroyed {
        owner_agent_id: &'a String,
        wasm_hash: &'a String,
        reason: &'a String,
        fee_kind: &'a ResourceKind,
        fee_amount: &'a i64,
    },
    ModuleArtifactBidPlaced {
        bidder_agent_id: &'a String,
        wasm_hash: &'a String,
        order_id: &'a u64,
        price_kind: &'a ResourceKind,
        price_amount: &'a i64,
    },
    ModuleArtifactBidCancelled {
        bidder_agent_id: &'a String,
        wasm_hash: &'a String,
        order_id: &'a u64,
        reason: &'a String,
    },
    ModuleArtifactSaleCompleted {
        buyer_agent_id: &'a String,
        seller_agent_id: &'a String,
        wasm_hash: &'a String,
        price_kind: &'a ResourceKind,
        price_amount: &'a i64,
        sale_id: &'a u64,
        listing_order_id: &'a Option<u64>,
        bid_order_id: &'a Option<u64>,
    },
}

impl<'a> ModuleLifecycleView<'a> {
    pub(super) fn from_event(event: &'a DomainEvent) -> Self {
        match event {
            DomainEvent::ModuleArtifactDeployed {
                publisher_agent_id,
                wasm_hash,
                bytes_len,
                fee_kind,
                fee_amount,
            } => Self::ModuleArtifactDeployed {
                publisher_agent_id,
                wasm_hash,
                bytes_len,
                fee_kind,
                fee_amount,
            },
            DomainEvent::ModuleInstalled {
                installer_agent_id,
                instance_id,
                module_id,
                module_version,
                wasm_hash,
                install_target,
                active,
                proposal_id,
                manifest_hash,
                fee_kind,
                fee_amount,
            } => Self::ModuleInstalled {
                installer_agent_id,
                instance_id,
                module_id,
                module_version,
                wasm_hash,
                install_target,
                active,
                proposal_id,
                manifest_hash,
                fee_kind,
                fee_amount,
            },
            DomainEvent::ModuleUpgraded {
                upgrader_agent_id,
                instance_id,
                module_id,
                from_module_version,
                to_module_version,
                wasm_hash,
                install_target,
                active,
                proposal_id,
                manifest_hash,
                fee_kind,
                fee_amount,
            } => Self::ModuleUpgraded {
                upgrader_agent_id,
                instance_id,
                module_id,
                from_module_version,
                to_module_version,
                wasm_hash,
                install_target,
                active,
                proposal_id,
                manifest_hash,
                fee_kind,
                fee_amount,
            },
            DomainEvent::ModuleReleaseRequested {
                request_id,
                requester_agent_id,
                manifest,
                activate,
                install_target,
                required_roles,
                profile_changes,
            } => Self::ModuleReleaseRequested {
                request_id,
                requester_agent_id,
                manifest,
                activate,
                install_target,
                required_roles,
                profile_changes,
            },
            DomainEvent::ModuleReleaseShadowed {
                request_id,
                operator_agent_id,
                manifest_hash,
            } => Self::ModuleReleaseShadowed {
                request_id,
                operator_agent_id,
                manifest_hash,
            },
            DomainEvent::ModuleReleaseAttested {
                request_id,
                operator_agent_id,
                signer_node_id,
                platform,
                build_manifest_hash,
                source_hash,
                wasm_hash,
                proof_cid,
                builder_image_digest,
                container_platform,
                canonicalizer_version,
            } => Self::ModuleReleaseAttested {
                request_id,
                operator_agent_id,
                signer_node_id,
                platform,
                build_manifest_hash,
                source_hash,
                wasm_hash,
                proof_cid,
                builder_image_digest,
                container_platform,
                canonicalizer_version,
            },
            DomainEvent::ModuleReleaseRoleApproved {
                request_id,
                approver_agent_id,
                role,
            } => Self::ModuleReleaseRoleApproved {
                request_id,
                approver_agent_id,
                role,
            },
            DomainEvent::ModuleReleaseRolesBound {
                operator_agent_id,
                target_agent_id,
                roles,
            } => Self::ModuleReleaseRolesBound {
                operator_agent_id,
                target_agent_id,
                roles,
            },
            DomainEvent::ModuleReleaseRejected {
                request_id,
                rejector_agent_id,
                reason,
            } => Self::ModuleReleaseRejected {
                request_id,
                rejector_agent_id,
                reason,
            },
            DomainEvent::ModuleReleaseApplied {
                request_id,
                operator_agent_id,
                installer_agent_id,
                instance_id,
                module_id,
                module_version,
                proposal_id,
                manifest_hash,
            } => Self::ModuleReleaseApplied {
                request_id,
                operator_agent_id,
                installer_agent_id,
                instance_id,
                module_id,
                module_version,
                proposal_id,
                manifest_hash,
            },
            DomainEvent::ModuleRollbackApplied {
                operator_agent_id,
                instance_id,
                module_id,
                from_module_version,
                to_module_version,
                wasm_hash,
                from_wasm_hash,
                from_release_request_id,
                install_target,
                active,
                proposal_id,
                manifest_hash,
                fee_kind,
                fee_amount,
            } => Self::ModuleRollbackApplied {
                operator_agent_id,
                instance_id,
                module_id,
                from_module_version,
                to_module_version,
                wasm_hash,
                from_wasm_hash,
                from_release_request_id,
                install_target,
                active,
                proposal_id,
                manifest_hash,
                fee_kind,
                fee_amount,
            },
            DomainEvent::ModuleArtifactListed {
                seller_agent_id,
                wasm_hash,
                price_kind,
                price_amount,
                order_id,
                fee_kind,
                fee_amount,
            } => Self::ModuleArtifactListed {
                seller_agent_id,
                wasm_hash,
                price_kind,
                price_amount,
                order_id,
                fee_kind,
                fee_amount,
            },
            DomainEvent::ModuleArtifactDelisted {
                seller_agent_id,
                wasm_hash,
                order_id,
                fee_kind,
                fee_amount,
            } => Self::ModuleArtifactDelisted {
                seller_agent_id,
                wasm_hash,
                order_id,
                fee_kind,
                fee_amount,
            },
            DomainEvent::ModuleArtifactDestroyed {
                owner_agent_id,
                wasm_hash,
                reason,
                fee_kind,
                fee_amount,
            } => Self::ModuleArtifactDestroyed {
                owner_agent_id,
                wasm_hash,
                reason,
                fee_kind,
                fee_amount,
            },
            DomainEvent::ModuleArtifactBidPlaced {
                bidder_agent_id,
                wasm_hash,
                order_id,
                price_kind,
                price_amount,
            } => Self::ModuleArtifactBidPlaced {
                bidder_agent_id,
                wasm_hash,
                order_id,
                price_kind,
                price_amount,
            },
            DomainEvent::ModuleArtifactBidCancelled {
                bidder_agent_id,
                wasm_hash,
                order_id,
                reason,
            } => Self::ModuleArtifactBidCancelled {
                bidder_agent_id,
                wasm_hash,
                order_id,
                reason,
            },
            DomainEvent::ModuleArtifactSaleCompleted {
                buyer_agent_id,
                seller_agent_id,
                wasm_hash,
                price_kind,
                price_amount,
                sale_id,
                listing_order_id,
                bid_order_id,
            } => Self::ModuleArtifactSaleCompleted {
                buyer_agent_id,
                seller_agent_id,
                wasm_hash,
                price_kind,
                price_amount,
                sale_id,
                listing_order_id,
                bid_order_id,
            },
            _ => unreachable!("event was routed to the wrong module_lifecycle view"),
        }
    }
}
