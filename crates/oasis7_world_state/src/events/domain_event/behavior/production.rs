use super::super::*;

#[derive(Debug, PartialEq)]
pub(super) enum ProductionView<'a> {
    FactoryBuildStarted {
        job_id: &'a ActionId,
        builder_agent_id: &'a String,
        site_id: &'a String,
        spec: &'a FactoryModuleSpec,
        consume_ledger: &'a MaterialLedgerId,
        ready_at: &'a WorldTime,
        contract_version: &'a Option<u8>,
        site_authority_revision: &'a Option<u64>,
        site_location_id: &'a Option<String>,
        location_anchor_revision: &'a Option<u64>,
        construction_power_obligation: &'a Option<FactoryBuildPowerObligationV1>,
    },
    FactoryBuilt {
        job_id: &'a ActionId,
        builder_agent_id: &'a String,
        site_id: &'a String,
        spec: &'a FactoryModuleSpec,
    },
    FactoryDurabilityChanged {
        factory_id: &'a String,
        previous_durability_ppm: &'a i64,
        durability_ppm: &'a i64,
        reason: &'a String,
    },
    FactoryMaintained {
        operator_agent_id: &'a String,
        factory_id: &'a String,
        consume_ledger: &'a MaterialLedgerId,
        consumed_parts: &'a i64,
        durability_ppm: &'a i64,
    },
    FactoryRecycled {
        operator_agent_id: &'a String,
        factory_id: &'a String,
        recycle_ledger: &'a MaterialLedgerId,
        recovered: &'a Vec<MaterialStack>,
        durability_ppm: &'a i64,
    },
    RecipeStarted {
        emergency_power_obligation: &'a Option<String>,
        committed_recipe_origin: &'a Option<CommittedRecipeOrigin>,
        job_id: &'a ActionId,
        requester_agent_id: &'a String,
        factory_id: &'a String,
        recipe_id: &'a String,
        accepted_batches: &'a u32,
        consume: &'a Vec<MaterialStack>,
        produce: &'a Vec<MaterialStack>,
        byproducts: &'a Vec<MaterialStack>,
        power_required: &'a i64,
        power_owner_agent_id: &'a Option<String>,
        duration_ticks: &'a u32,
        consume_ledger: &'a MaterialLedgerId,
        output_ledger: &'a MaterialLedgerId,
        bottleneck_tags: &'a Vec<String>,
        market_quotes: &'a Vec<MaterialMarketQuote>,
        logistics_route_ids: &'a Vec<String>,
        logistics_path_ids: &'a Vec<String>,
        ready_at: &'a WorldTime,
    },
    RecipeCompleted {
        committed_recipe_origin: &'a Option<CommittedRecipeOrigin>,
        job_id: &'a ActionId,
        requester_agent_id: &'a String,
        factory_id: &'a String,
        recipe_id: &'a String,
        accepted_batches: &'a u32,
        produce: &'a Vec<MaterialStack>,
        byproducts: &'a Vec<MaterialStack>,
        output_ledger: &'a MaterialLedgerId,
        bottleneck_tags: &'a Vec<String>,
        logistics_route_ids: &'a Vec<String>,
        logistics_path_ids: &'a Vec<String>,
    },
    FactoryProductionBlocked {
        action_id: &'a ActionId,
        requester_agent_id: &'a String,
        factory_id: &'a String,
        recipe_id: &'a String,
        blocker_kind: &'a String,
        blocker_detail: &'a String,
    },
    FactoryProductionResumed {
        job_id: &'a ActionId,
        requester_agent_id: &'a String,
        factory_id: &'a String,
        recipe_id: &'a String,
        previous_blocked_at: &'a Option<WorldTime>,
        previous_blocker_kind: &'a Option<String>,
        previous_blocker_detail: &'a Option<String>,
    },
    FactoryProductionPaused {
        action_id: &'a ActionId,
        requester_agent_id: &'a String,
        factory_id: &'a String,
        reason: &'a String,
    },
}

impl<'a> ProductionView<'a> {
    pub(super) fn from_event(event: &'a DomainEvent) -> Self {
        match event {
            DomainEvent::FactoryBuildStarted {
                job_id,
                builder_agent_id,
                site_id,
                spec,
                consume_ledger,
                ready_at,
                contract_version,
                site_authority_revision,
                site_location_id,
                location_anchor_revision,
                construction_power_obligation,
            } => Self::FactoryBuildStarted {
                job_id,
                builder_agent_id,
                site_id,
                spec,
                consume_ledger,
                ready_at,
                contract_version,
                site_authority_revision,
                site_location_id,
                location_anchor_revision,
                construction_power_obligation,
            },
            DomainEvent::FactoryBuilt {
                job_id,
                builder_agent_id,
                site_id,
                spec,
            } => Self::FactoryBuilt {
                job_id,
                builder_agent_id,
                site_id,
                spec,
            },
            DomainEvent::FactoryDurabilityChanged {
                factory_id,
                previous_durability_ppm,
                durability_ppm,
                reason,
            } => Self::FactoryDurabilityChanged {
                factory_id,
                previous_durability_ppm,
                durability_ppm,
                reason,
            },
            DomainEvent::FactoryMaintained {
                operator_agent_id,
                factory_id,
                consume_ledger,
                consumed_parts,
                durability_ppm,
            } => Self::FactoryMaintained {
                operator_agent_id,
                factory_id,
                consume_ledger,
                consumed_parts,
                durability_ppm,
            },
            DomainEvent::FactoryRecycled {
                operator_agent_id,
                factory_id,
                recycle_ledger,
                recovered,
                durability_ppm,
            } => Self::FactoryRecycled {
                operator_agent_id,
                factory_id,
                recycle_ledger,
                recovered,
                durability_ppm,
            },
            DomainEvent::RecipeStarted {
                emergency_power_obligation,
                committed_recipe_origin,
                job_id,
                requester_agent_id,
                factory_id,
                recipe_id,
                accepted_batches,
                consume,
                produce,
                byproducts,
                power_required,
                power_owner_agent_id,
                duration_ticks,
                consume_ledger,
                output_ledger,
                bottleneck_tags,
                market_quotes,
                logistics_route_ids,
                logistics_path_ids,
                ready_at,
            } => Self::RecipeStarted {
                emergency_power_obligation,
                committed_recipe_origin,
                job_id,
                requester_agent_id,
                factory_id,
                recipe_id,
                accepted_batches,
                consume,
                produce,
                byproducts,
                power_required,
                power_owner_agent_id,
                duration_ticks,
                consume_ledger,
                output_ledger,
                bottleneck_tags,
                market_quotes,
                logistics_route_ids,
                logistics_path_ids,
                ready_at,
            },
            DomainEvent::RecipeCompleted {
                committed_recipe_origin,
                job_id,
                requester_agent_id,
                factory_id,
                recipe_id,
                accepted_batches,
                produce,
                byproducts,
                output_ledger,
                bottleneck_tags,
                logistics_route_ids,
                logistics_path_ids,
            } => Self::RecipeCompleted {
                committed_recipe_origin,
                job_id,
                requester_agent_id,
                factory_id,
                recipe_id,
                accepted_batches,
                produce,
                byproducts,
                output_ledger,
                bottleneck_tags,
                logistics_route_ids,
                logistics_path_ids,
            },
            DomainEvent::FactoryProductionBlocked {
                action_id,
                requester_agent_id,
                factory_id,
                recipe_id,
                blocker_kind,
                blocker_detail,
            } => Self::FactoryProductionBlocked {
                action_id,
                requester_agent_id,
                factory_id,
                recipe_id,
                blocker_kind,
                blocker_detail,
            },
            DomainEvent::FactoryProductionResumed {
                job_id,
                requester_agent_id,
                factory_id,
                recipe_id,
                previous_blocked_at,
                previous_blocker_kind,
                previous_blocker_detail,
            } => Self::FactoryProductionResumed {
                job_id,
                requester_agent_id,
                factory_id,
                recipe_id,
                previous_blocked_at,
                previous_blocker_kind,
                previous_blocker_detail,
            },
            DomainEvent::FactoryProductionPaused {
                action_id,
                requester_agent_id,
                factory_id,
                reason,
            } => Self::FactoryProductionPaused {
                action_id,
                requester_agent_id,
                factory_id,
                reason,
            },
            _ => unreachable!("event was routed to the wrong production view"),
        }
    }
}
