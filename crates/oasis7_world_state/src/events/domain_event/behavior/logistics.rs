use super::super::*;

#[derive(Debug, PartialEq)]
pub(super) enum LogisticsView<'a> {
    MaterialTransferred {
        transfer_id: &'a Option<ActionId>,
        requester_agent_id: &'a String,
        from_ledger: &'a MaterialLedgerId,
        to_ledger: &'a MaterialLedgerId,
        kind: &'a String,
        amount: &'a i64,
        distance_km: &'a i64,
        priority: &'a MaterialTransitPriority,
        route_id: &'a Option<String>,
    },
    LogisticsRouteRegistered {
        requester_agent_id: &'a String,
        route_id: &'a Option<String>,
        from_ledger: &'a MaterialLedgerId,
        to_ledger: &'a MaterialLedgerId,
        kind: &'a String,
        distance_km: &'a i64,
        priority: &'a MaterialTransitPriority,
        owner_agent_id: &'a String,
        available: &'a bool,
        capacity_units: &'a i64,
        tariff_electricity_per_unit: &'a i64,
    },
    LogisticsRouteAvailabilityChanged {
        requester_agent_id: &'a String,
        route_id: &'a String,
        available: &'a bool,
        owner_agent_id: &'a String,
    },
    LogisticsPathRerouted {
        requester_agent_id: &'a String,
        job_id: &'a ActionId,
        original_path_id: &'a Option<String>,
        original_route_ids: &'a Vec<String>,
        effective_path_id: &'a Option<String>,
        effective_route_ids: &'a Vec<String>,
        reason: &'a String,
        reroute_count: &'a u32,
        tariff_electricity_total: &'a i64,
        owner_payouts: &'a Vec<LogisticsOwnerPayout>,
        governance_tax_electricity: &'a i64,
    },
    MaterialTransitStarted {
        job_id: &'a ActionId,
        requester_agent_id: &'a String,
        from_ledger: &'a MaterialLedgerId,
        to_ledger: &'a MaterialLedgerId,
        kind: &'a String,
        amount: &'a i64,
        distance_km: &'a i64,
        loss_bps: &'a i64,
        ready_at: &'a WorldTime,
        priority: &'a MaterialTransitPriority,
        route_id: &'a Option<String>,
        path_id: &'a Option<String>,
        route_ids: &'a Vec<String>,
        tariff_electricity_total: &'a i64,
        reroute_count: &'a u32,
    },
    MaterialTransitCompleted {
        job_id: &'a ActionId,
        requester_agent_id: &'a String,
        from_ledger: &'a MaterialLedgerId,
        to_ledger: &'a MaterialLedgerId,
        kind: &'a String,
        sent_amount: &'a i64,
        received_amount: &'a i64,
        loss_amount: &'a i64,
        distance_km: &'a i64,
        priority: &'a MaterialTransitPriority,
        route_id: &'a Option<String>,
        path_id: &'a Option<String>,
        route_ids: &'a Vec<String>,
        tariff_electricity_total: &'a i64,
        reroute_count: &'a u32,
    },
}

impl<'a> LogisticsView<'a> {
    pub(super) fn from_event(event: &'a DomainEvent) -> Self {
        match event {
            DomainEvent::MaterialTransferred {
                transfer_id,
                requester_agent_id,
                from_ledger,
                to_ledger,
                kind,
                amount,
                distance_km,
                priority,
                route_id,
            } => Self::MaterialTransferred {
                transfer_id,
                requester_agent_id,
                from_ledger,
                to_ledger,
                kind,
                amount,
                distance_km,
                priority,
                route_id,
            },
            DomainEvent::LogisticsRouteRegistered {
                requester_agent_id,
                route_id,
                from_ledger,
                to_ledger,
                kind,
                distance_km,
                priority,
                owner_agent_id,
                available,
                capacity_units,
                tariff_electricity_per_unit,
            } => Self::LogisticsRouteRegistered {
                requester_agent_id,
                route_id,
                from_ledger,
                to_ledger,
                kind,
                distance_km,
                priority,
                owner_agent_id,
                available,
                capacity_units,
                tariff_electricity_per_unit,
            },
            DomainEvent::LogisticsRouteAvailabilityChanged {
                requester_agent_id,
                route_id,
                available,
                owner_agent_id,
            } => Self::LogisticsRouteAvailabilityChanged {
                requester_agent_id,
                route_id,
                available,
                owner_agent_id,
            },
            DomainEvent::LogisticsPathRerouted {
                requester_agent_id,
                job_id,
                original_path_id,
                original_route_ids,
                effective_path_id,
                effective_route_ids,
                reason,
                reroute_count,
                tariff_electricity_total,
                owner_payouts,
                governance_tax_electricity,
            } => Self::LogisticsPathRerouted {
                requester_agent_id,
                job_id,
                original_path_id,
                original_route_ids,
                effective_path_id,
                effective_route_ids,
                reason,
                reroute_count,
                tariff_electricity_total,
                owner_payouts,
                governance_tax_electricity,
            },
            DomainEvent::MaterialTransitStarted {
                job_id,
                requester_agent_id,
                from_ledger,
                to_ledger,
                kind,
                amount,
                distance_km,
                loss_bps,
                ready_at,
                priority,
                route_id,
                path_id,
                route_ids,
                tariff_electricity_total,
                reroute_count,
            } => Self::MaterialTransitStarted {
                job_id,
                requester_agent_id,
                from_ledger,
                to_ledger,
                kind,
                amount,
                distance_km,
                loss_bps,
                ready_at,
                priority,
                route_id,
                path_id,
                route_ids,
                tariff_electricity_total,
                reroute_count,
            },
            DomainEvent::MaterialTransitCompleted {
                job_id,
                requester_agent_id,
                from_ledger,
                to_ledger,
                kind,
                sent_amount,
                received_amount,
                loss_amount,
                distance_km,
                priority,
                route_id,
                path_id,
                route_ids,
                tariff_electricity_total,
                reroute_count,
            } => Self::MaterialTransitCompleted {
                job_id,
                requester_agent_id,
                from_ledger,
                to_ledger,
                kind,
                sent_amount,
                received_amount,
                loss_amount,
                distance_km,
                priority,
                route_id,
                path_id,
                route_ids,
                tariff_electricity_total,
                reroute_count,
            },
            _ => unreachable!("event was routed to the wrong logistics view"),
        }
    }
}
