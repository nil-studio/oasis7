#[derive(Clone, Copy)]
pub enum DiplomacyScalarV1 {
    Alliance(AllianceScalarV1),
    War(WarScalarV1),
    Crisis(CrisisScalarV1),
    Contract(ContractScalarV1),
}
impl DiplomacyScalarV1 {
    pub(super) fn slot(self, field: DiplomacyFieldV1) -> Result<usize, ValueTreeError> {
        Ok(match (self, field) {
            (Self::Alliance(v), DiplomacyFieldV1::Alliances) => match v {
                AllianceScalarV1::AllianceId => 1,
                AllianceScalarV1::Charter => 4,
                AllianceScalarV1::FormedByAgentId => 5,
                AllianceScalarV1::FormedAt => 6,
            },
            (Self::War(v), DiplomacyFieldV1::Wars) => match v {
                WarScalarV1::WarId => 1,
                WarScalarV1::InitiatorAgentId => 2,
                WarScalarV1::AggressorAllianceId => 3,
                WarScalarV1::DefenderAllianceId => 4,
                WarScalarV1::Objective => 5,
                WarScalarV1::Intensity => 6,
                WarScalarV1::Active => 7,
                WarScalarV1::DeclaredMobilizationElectricityCost => 8,
                WarScalarV1::DeclaredMobilizationDataCost => 9,
                WarScalarV1::MaxDurationTicks => 10,
                WarScalarV1::AggressorScore => 11,
                WarScalarV1::DefenderScore => 12,
                WarScalarV1::ConcludedAt => 14,
                WarScalarV1::WinnerAllianceId => 16,
                WarScalarV1::LoserAllianceId => 18,
                WarScalarV1::SettlementSummary => 20,
                WarScalarV1::DeclaredAt => 23,
            },
            (Self::Crisis(v), DiplomacyFieldV1::Crises) => match v {
                CrisisScalarV1::CrisisId => 1,
                CrisisScalarV1::Kind => 2,
                CrisisScalarV1::Severity => 3,
                CrisisScalarV1::Status => 4,
                CrisisScalarV1::OpenedAt => 5,
                CrisisScalarV1::ExpiresAt => 6,
                CrisisScalarV1::ResolverAgentId => 8,
                CrisisScalarV1::Strategy => 10,
                CrisisScalarV1::Success => 12,
                CrisisScalarV1::Impact => 13,
                CrisisScalarV1::ResolvedAt => 15,
            },
            (Self::Contract(v), DiplomacyFieldV1::EconomicContracts) => match v {
                ContractScalarV1::ContractId => 1,
                ContractScalarV1::CreatorAgentId => 2,
                ContractScalarV1::CounterpartyAgentId => 3,
                ContractScalarV1::FulfillmentKind => 4,
                ContractScalarV1::SettlementKind => 5,
                ContractScalarV1::SettlementAmount => 6,
                ContractScalarV1::ReputationStake => 7,
                ContractScalarV1::ExpiresAt => 8,
                ContractScalarV1::Description => 9,
                ContractScalarV1::Status => 10,
                ContractScalarV1::AcceptedAt => 12,
                ContractScalarV1::SettledAt => 14,
                ContractScalarV1::SettlementSuccess => 16,
                ContractScalarV1::TransferAmount => 17,
                ContractScalarV1::TaxAmount => 18,
                ContractScalarV1::SettlementNotes => 20,
            },
            _ => return Err(ValueTreeError::Invalid("diplomacy scalar owner")),
        })
    }
}
