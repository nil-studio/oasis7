pub(super) fn specs(field: DiplomacyFieldV1) -> &'static [Spec] {
    match field {
        DiplomacyFieldV1::Alliances => &ALLIANCE,
        DiplomacyFieldV1::Wars => &WAR,
        DiplomacyFieldV1::Crises => &CRISIS,
        DiplomacyFieldV1::EconomicContracts => &CONTRACT,
    }
}
