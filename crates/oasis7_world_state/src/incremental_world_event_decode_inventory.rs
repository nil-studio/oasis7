fn normalized_sha256(bytes: &[u8]) -> [u8; 32] {
    let mut hash = Sha256::new();
    let mut start = 0;
    let mut i = 0;
    while i + 1 < bytes.len() {
        if bytes[i] == b'\r' && bytes[i + 1] == b'\n' {
            hash.update(&bytes[start..i]);
            start = i + 1;
        }
        i += 1;
    }
    hash.update(&bytes[start..]);
    hash.finalize().into()
}
/// Call before any typed deserialize/allocation admission based on the layout
/// table. A false result is terminal until the inventory has been re-audited.
/// This is code inventory validation, not a proof of a decoded object.
pub(crate) fn world_event_layout_inventory_matches_v1() -> bool {
    static CHECKED: OnceLock<bool> = OnceLock::new();
    *CHECKED.get_or_init(|| {
        SOURCES
            .iter()
            .all(|(bytes, expected)| normalized_sha256(bytes) == *expected)
    })
}
